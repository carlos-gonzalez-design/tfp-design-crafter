<script setup>
// Muestra ejemplos de las capas CSS, resalta selectores y propiedades, y permite copiar el código visible.
import { computed, ref } from 'vue'
import DsButton from '../design-system/actions/DsButton.vue'
import DsTabs from '../design-system/navigation/DsTabs.vue'
import { createDefaultFoundations } from '../../data/defaultDesignSystem.js'
import { createDesignTokens } from '../../utils/designTokens.js'

const tabs = [
  { value: 'tokens', label: 'Design Tokens' },
  { value: 'component', label: 'Component CSS' },
  { value: 'all', label: 'Export All' },
]
const activeTab = ref('tokens')
const copied = ref(false)
const defaultTokens = createDesignTokens(createDefaultFoundations())

const tokenNames = [
  '--color-primary-source',
  '--color-primary-600',
  '--ds-color-bg-surface-default',
  '--ds-color-text-primary-default',
  '--ds-font-size-heading-primary',
  '--ds-spacing-card-padding',
  '--ds-radius-card-primary',
]
const tokenCss = `/* Generated by Design Crafter */
:root {
${tokenNames.map(name => `  ${name}: ${defaultTokens[name]};`).join('\n')}
}`
const componentCss = `.card {
  display: grid;
  gap: var(--ds-spacing-card-content-gap);
  padding: var(--ds-spacing-card-padding);
  border-radius: var(--ds-radius-card-primary);
  color: var(--ds-color-text-primary-default);
  background: var(--ds-color-bg-surface-default);
}

.card__title {
  font-size: var(--ds-font-size-heading-primary);
}

.card__button {
  color: var(--ds-color-button-primary-text-default);
  background: var(--ds-color-button-primary-background-default);
}`
const fullCss = `${tokenCss}

/* Component layer */
${componentCss}`
const codeByTab = { tokens: tokenCss, component: componentCss, all: fullCss }
const currentCode = computed(() => codeByTab[activeTab.value])
const exportLabel = computed(() => tabs.find(tab => tab.value === activeTab.value)?.label)
const previewTokens = createDesignTokens(createDefaultFoundations())

function escapeHtml(value) {
  // Escapa primero el contenido antes de añadir marcado para el resaltado sintáctico.
  return value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;')
}

const highlightedCode = computed(() => currentCode.value.split('\n').map(line => {
  const escaped = escapeHtml(line)
  if (escaped.trim().startsWith('/*')) return `<span class="code-comment">${escaped}</span>`
  return escaped
    .replace(/(^\s*)([.:#]?[a-z][\w-]*(?:__[\w-]+)?)(\s*\{)/i, '$1<span class="code-selector">$2</span>$3')
    .replace(/(--[\w-]+)/g, '<span class="code-property">$1</span>')
    .replace(/(#[\da-f]{3,8})\b/gi, '<span class="code-value">$1</span>')
    .replace(/\b(var|color-mix)(?=\()/g, '<span class="code-function">$1</span>')
} ).join('\n'))

async function copyCss() {
  try {
    if (!navigator.clipboard?.writeText) throw new Error('Clipboard API unavailable')
    await navigator.clipboard.writeText(currentCode.value)
  } catch {
    // El textarea temporal ofrece una alternativa cuando el navegador no expone Clipboard API.
    const textarea = document.createElement('textarea')
    textarea.value = currentCode.value
    textarea.setAttribute('readonly', '')
    textarea.style.position = 'fixed'
    textarea.style.opacity = '0'
    document.body.append(textarea)
    textarea.select()
    const copiedWithFallback = document.execCommand('copy')
    textarea.remove()
    if (!copiedWithFallback) return
  }
  copied.value = true
  window.setTimeout(() => { copied.value = false }, 1600)
}
</script>

<template>
  <section class="landing-section css-showcase" aria-labelledby="css-showcase-title">
    <div class="landing-container css-showcase__grid">
      <div class="css-showcase__copy" data-reveal>
        <p class="landing-eyebrow"><span></span>03 · Design to code</p>
        <h2 id="css-showcase-title">From visual decisions<br />to clean CSS.</h2>
        <p>Export your design tokens and component styles as clean, reusable CSS. Built with semantic variables and BEM conventions.</p>
        <ul>
          <li><span>✓</span> CSS custom properties</li>
          <li><span>✓</span> Semantic design tokens</li>
          <li><span>✓</span> Component-ready BEM classes</li>
        </ul>
        <p class="css-showcase__note">The preview below uses the project’s real token transformation and representative component CSS.</p>
      </div>

      <div class="css-showcase__editor ds-theme" :style="previewTokens" data-reveal>
        <div class="code-window__bar" aria-hidden="true"><span></span><span></span><span></span><p>tokens.css</p><i>CSS</i></div>
        <DsTabs v-model="activeTab" :tabs="tabs" label="CSS export options">
          <template v-for="tab in tabs" :key="tab.value" #[`panel-${tab.value}`]>
            <div class="code-window">
              <div class="code-window__meta">
                <span>{{ exportLabel }}</span>
                <DsButton variant="ghost" size="small" @click="copyCss">{{ copied ? 'Copied!' : 'Copy CSS' }}</DsButton>
              </div>
              <pre tabindex="0" :aria-label="`${exportLabel} CSS code`"><code v-html="highlightedCode"></code></pre>
              <span class="sr-only" aria-live="polite">{{ copied ? 'CSS copied to clipboard' : '' }}</span>
            </div>
          </template>
        </DsTabs>
      </div>
    </div>
  </section>
</template>
